import re
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from api.models import IFACE_NAME_PATTERN, WireGuardKey

FWMARK_PATTERN = re.compile(r"^(off|0x[0-9a-fA-F]{1,8}|[0-9]{1,10})$")


class Interface(BaseModel):
    """Runtime view of a WireGuard interface, as reported by `wg show`."""

    name: str = Field(
        description="Interface name. Any free-form string [a-zA-Z0-9_=+.-]{1,15} will work. "
        "Recommended names include 'wg0' or 'wgvpn0' or even 'wgmgmtlan0'.",
    )
    status: Literal["up", "down"] = Field(
        description="Whether the interface is currently running ('up') or only exists as a config file ('down'). "
        "Runtime fields are only populated when the interface is up.",
    )
    public_key: WireGuardKey | None = Field(
        None,
        description="The base64 public key derived from the interface's private key.",
    )
    listen_port: int | None = Field(
        None,
        ge=1,
        le=65535,
        description="The UDP port the interface is listening on.",
    )
    fw_mark: str | None = Field(
        None,
        description="The fwmark applied to outgoing packets, or null if disabled.",
    )
    num_peers: int = Field(
        0,
        description="Number of peers currently configured on this interface.",
    )

    @field_validator("name")
    @classmethod
    def validate_name(cls, v: str) -> str:
        if not IFACE_NAME_PATTERN.match(v):
            raise ValueError("Interface name must be 1-15 chars matching [a-zA-Z0-9_=+.-]")
        return v


class InterfaceUpdate(BaseModel):
    """Runtime settings applied with `wg set`. Omitted fields are left unchanged."""

    model_config = ConfigDict(extra="forbid")

    private_key: WireGuardKey | None = Field(
        None,
        description="A base64 private key generated by wg genkey.",
        json_schema_extra={"writeOnly": True},
    )
    listen_port: int | None = Field(
        None,
        ge=1,
        le=65535,
        description="A 16-bit port for listening.",
    )
    fw_mark: str | None = Field(
        None,
        description="A 32-bit fwmark for outgoing packets. If set to 0 or 'off', this option is disabled. "
        "May be specified in hexadecimal by prepending '0x'.",
    )

    @field_validator("fw_mark")
    @classmethod
    def validate_fw_mark(cls, v: str | None) -> str | None:
        if v is not None and not FWMARK_PATTERN.match(v):
            raise ValueError("fw_mark must be 'off', a decimal number or a hex number prefixed with '0x'")
        return v


class InterfaceAction(BaseModel):
    """Result of a wg-quick lifecycle action."""

    status: Literal["up", "down", "saved"] = Field(description="The action that was applied.")
    interface: str = Field(description="Interface name.")
