import re
from ipaddress import IPv4Address, IPv6Address, ip_network

from pydantic import BaseModel, ConfigDict, Field, field_validator

from api.models import WireGuardKey

# host:port, where host is an IPv4 address, a hostname or a bracketed IPv6 address.
ENDPOINT_PATTERN = re.compile(r"^(?:\[(?P<ipv6>[^\[\]]+)\]|(?P<host>[^:\[\]]+)):(?P<port>[0-9]{1,5})$")
HOSTNAME_PATTERN = re.compile(
    r"^(?=.{1,253}$)[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$"
)

ALLOWED_IPS_DESCRIPTION = (
    "A comma-separated list of IP (v4 or v6) addresses with CIDR masks from which incoming traffic for this peer "
    "is allowed and to which outgoing traffic for this peer is directed. The catch-all 0.0.0.0/0 may be specified "
    "for matching all IPv4 addresses, and ::/0 may be specified for matching all IPv6 addresses."
)
ENDPOINT_DESCRIPTION = (
    "An endpoint IP or hostname, followed by a colon, and then a port number. IPv6 addresses go in brackets. "
    "This endpoint will be updated automatically to the most recent source IP address and port "
    "of correctly authenticated packets from the peer."
)
KEEPALIVE_DESCRIPTION = (
    "A seconds interval, between 1 and 65535 inclusive, of how often to send an authenticated empty packet "
    "to the peer for the purpose of keeping a stateful firewall or NAT mapping valid persistently. "
    "0 disables it."
)


class Peer(BaseModel):
    """Runtime view of a peer, as reported by `wg show`. The preshared key is never returned."""

    public_key: str = Field(description="The peer's base64 public key.")
    allowed_ips: str | None = Field(None, description=ALLOWED_IPS_DESCRIPTION)
    endpoint: str | None = Field(None, description=ENDPOINT_DESCRIPTION)
    persistent_keepalive: int | None = Field(None, description=KEEPALIVE_DESCRIPTION)
    latest_handshake: int | None = Field(None, description="Unix timestamp of the most recent handshake.")
    transfer_rx: int | None = Field(None, description="Number of bytes received from this peer.")
    transfer_tx: int | None = Field(None, description="Number of bytes transmitted to this peer.")


class _PeerSettings(BaseModel):
    """Fields shared by PeerCreate and PeerUpdate. Each declares allowed_ips with its own requiredness."""

    model_config = ConfigDict(extra="forbid")

    endpoint: str | None = Field(None, description=ENDPOINT_DESCRIPTION)
    preshared_key: WireGuardKey | None = Field(
        None,
        description="A base64 preshared key generated by wg genpsk. This option adds an additional layer of "
        "symmetric-key cryptography to be mixed into the already existing public-key cryptography, "
        "for post-quantum resistance. Write-only: it is never returned.",
        json_schema_extra={"writeOnly": True},
    )
    persistent_keepalive: int | None = Field(None, ge=0, le=65535, description=KEEPALIVE_DESCRIPTION)

    @field_validator("allowed_ips", check_fields=False)
    @classmethod
    def validate_allowed_ips(cls, v: str | None) -> str | None:
        if v is not None:
            for cidr in v.split(","):
                try:
                    ip_network(cidr.strip(), strict=False)
                except ValueError:
                    raise ValueError(f"Invalid CIDR notation: {cidr.strip()}") from None
        return v

    @field_validator("endpoint")
    @classmethod
    def validate_endpoint(cls, v: str | None) -> str | None:
        if v is not None and not _is_valid_endpoint(v):
            raise ValueError("Invalid endpoint: expected IPv4:port, [IPv6]:port or hostname:port")
        return v


class PeerCreate(_PeerSettings):
    """A new peer, added with `wg set`. public_key and allowed_ips are required."""

    public_key: WireGuardKey = Field(description="A base64 public key calculated by wg pubkey.")
    allowed_ips: str = Field(description=ALLOWED_IPS_DESCRIPTION)


class PeerUpdate(_PeerSettings):
    """Peer settings applied with `wg set`. Omitted fields are left unchanged."""

    allowed_ips: str | None = Field(None, description=ALLOWED_IPS_DESCRIPTION)


def _is_valid_endpoint(endpoint: str) -> bool:
    match = ENDPOINT_PATTERN.match(endpoint)
    if not match or not 1 <= int(match["port"]) <= 65535:
        return False
    if match["ipv6"] is not None:
        try:
            IPv6Address(match["ipv6"])
        except ValueError:
            return False
        return True
    try:
        IPv4Address(match["host"])
    except ValueError:
        return bool(HOSTNAME_PATTERN.match(match["host"]))
    return True
